class aluno:
  def __init__(self, nome,nota1=0,nota2=0):
    self.nome = nome
    self.nota1 = nota1
    self.nota2 = nota2

  def calcular_media(self,nota1,nota2):
    if nota1 + nota2 > 0:
      self.media = (nota1 + nota2) / 2
      return self.media
    else:
      return 0
  def verificar_situacao(self):
    if self.media >= 7:
      return "Aprovado"
    else:
      return "Reprovado"

nome = input("Nome do aluno: ")
nota1 = float(input("Primeira nota: "))
nota2 = float(input("Segunda nota: "))

aluno1 = aluno(nome,nota1,nota2)
aluno1.calcular_media(nota1,nota2)

print("\nAluno: ", aluno1.nome)
print("Nota 1: ", aluno1.nota1)
print("Nota 2: ", aluno1.nota2)
print("Média: ", aluno1.media)
print("Situação: ", aluno1.verificar_situacao())